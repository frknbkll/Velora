"""Build smaller product-photo downloads without changing the original photos.

Run from any directory with ``python tools/prepare-responsive-images.py``.
Only gallery images referenced by the current catalog/color map are processed.
Originals remain available for enlarged product views and high-density displays.
"""

from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import re

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parent.parent
GALLERY = (ROOT / "assets" / "gallery").resolve()
DESTINATION = (ROOT / "assets" / "responsive").resolve()
WIDTHS = (480, 960)
QUALITY = 82
RECIPE = f"webp-v1-quality-{QUALITY}-method-6-exif-transpose".encode("ascii")
IMAGE_REFERENCE = re.compile(r'assets/gallery/[^"\s<>]+\.(?:jpg|jpeg|png)', re.I)


def referenced_images() -> list[str]:
    references: set[str] = set()
    for filename in ("product-catalog.json", "product-color-images.js"):
        references.update(IMAGE_REFERENCE.findall((ROOT / filename).read_text(encoding="utf-8")))
    return sorted(references)


def prepare(reference: str) -> tuple[str, dict, int, int, int]:
    source = (ROOT / reference).resolve()
    if not source.is_relative_to(GALLERY) or not source.is_file():
        raise ValueError(f"Referenced image is missing or outside the gallery: {reference}")
    source_bytes = source.read_bytes()
    fingerprint = hashlib.sha256(RECIPE + b"\0" + source_bytes).hexdigest()[:24]
    with Image.open(source) as photo:
        photo = ImageOps.exif_transpose(photo)
        if photo.mode not in ("RGB", "RGBA"):
            photo = photo.convert("RGBA" if "transparency" in photo.info else "RGB")
        width, height = photo.size
        candidates: list[tuple[str, int]] = []
        for target_width in sorted({min(width, requested) for requested in WIDTHS}):
            target = DESTINATION / f"{fingerprint}-{target_width}.webp"
            if not target.resolve().is_relative_to(DESTINATION):
                raise ValueError("Responsive image destination is outside its asset directory")
            if not target.exists():
                target_height = max(1, round(height * target_width / width))
                resized = photo.resize((target_width, target_height), Image.Resampling.LANCZOS)
                resized.save(target, "WEBP", quality=QUALITY, method=6)
            candidates.append((target.relative_to(ROOT).as_posix(), target_width))
        if width > candidates[-1][1]:
            candidates.append((reference, width))
    small_bytes = (ROOT / candidates[0][0]).stat().st_size
    generated_bytes = sum((ROOT / path).stat().st_size for path, _ in candidates if path != reference)
    return reference, {
        "src": candidates[0][0],
        "srcset": ", ".join(f"{path} {candidate_width}w" for path, candidate_width in candidates),
        "width": width,
        "height": height,
    }, len(source_bytes), small_bytes, generated_bytes


def main() -> None:
    if not DESTINATION.is_relative_to(ROOT):
        raise ValueError("Responsive image directory must be inside the project")
    DESTINATION.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=min(4, os.cpu_count() or 1)) as executor:
        results = list(executor.map(prepare, referenced_images()))
    manifest = {reference: details for reference, details, *_ in results}
    output = ROOT / "product-responsive-images.js"
    output.write_text(
        "// Generated by tools/prepare-responsive-images.py. Originals are retained for zoom.\n"
        "window.VeloraResponsiveImages = " + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    originals = sum(row[2] for row in results)
    small = sum(row[3] for row in results)
    generated = sum(row[4] for row in results)
    saving = (1 - small / originals) * 100 if originals else 0
    print(f"Prepared {len(results)} referenced images. Originals: {originals:,} bytes; "
          f"480px candidates: {small:,} bytes ({saving:.1f}% smaller); "
          f"all generated candidates: {generated:,} bytes.")


if __name__ == "__main__":
    main()
